# 1. IMPORT LIBRARIES

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import joblib

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression

from sklearn.metrics import (
    accuracy_score,
    confusion_matrix,
    classification_report
)

print("All libraries imported successfully!")

# 2. CREATE CUSTOMER CHURN DATASET AUTOMATICALLY

np.random.seed(42)

n = 500

data = pd.DataFrame({
    "gender": np.random.choice(["Male", "Female"], n),
    "SeniorCitizen": np.random.choice([0, 1], n),
    "Partner": np.random.choice(["Yes", "No"], n),
    "Dependents": np.random.choice(["Yes", "No"], n),
    "tenure": np.random.randint(1, 73, n),
    "MonthlyCharges": np.random.uniform(20, 120, n),
    "InternetService": np.random.choice(
        ["DSL", "Fiber optic", "No"], n
    ),
    "Contract": np.random.choice(
        ["Month-to-month", "One year", "Two year"], n
    ),
    "PaymentMethod": np.random.choice(
        ["Electronic check", "Mailed check",
         "Bank transfer", "Credit card"], n
    )
})

# Create churn target using customer characteristics

churn_score = (
    0.35 * (data["Contract"] == "Month-to-month").astype(int)
    + 0.30 * (data["tenure"] < 15).astype(int)
    + 0.20 * (data["MonthlyCharges"] > 85).astype(int)
    + 0.15 * (data["PaymentMethod"] == "Electronic check").astype(int)
    + 0.10 * (data["InternetService"] == "Fiber optic").astype(int)
)

probability = 1 / (1 + np.exp(-5 * (churn_score - 0.45)))

data["Churn"] = np.where(
    np.random.random(n) < probability, "Yes", "No"
)

print("\nDataset created successfully!")
print("\nFirst 5 Records:")
print(data.head())

print("\nDataset Shape:", data.shape)

# 3. CHECK DATA

print("\nMissing Values:")
print(data.isnull().sum())

print("\nChurn Distribution:")
print(data["Churn"].value_counts())

# 4. SEPARATE FEATURES AND TARGET

X = data.drop("Churn", axis=1)
y = data["Churn"].map({"No": 0, "Yes": 1})

# 5. IDENTIFY NUMERICAL AND CATEGORICAL FEATURES

numeric_features = X.select_dtypes(
    include=["int64", "float64"]
).columns.tolist()

categorical_features = X.select_dtypes(
    include=["object"]
).columns.tolist()

# 6. DATA PREPROCESSING

numeric_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

categorical_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer([
    ("numeric", numeric_pipeline, numeric_features),
    ("categorical", categorical_pipeline, categorical_features)
])

# 7. SPLIT DATA INTO TRAINING AND TESTING

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("\nTraining records:", len(X_train))
print("Testing records:", len(X_test))

# 8. BUILD LOGISTIC REGRESSION MODEL

model = Pipeline([
    ("preprocessor", preprocessor),
    ("classifier", LogisticRegression(max_iter=2000))
])

# 9. TRAIN MODEL

model.fit(X_train, y_train)

print("\nLogistic Regression Model Trained Successfully!")

# 10. PREDICT CUSTOMER CHURN

y_pred = model.predict(X_test)

# 11. MODEL ACCURACY

accuracy = accuracy_score(y_test, y_pred)

print("\n========== MODEL ACCURACY ==========")
print("Accuracy:", round(accuracy * 100, 2), "%")

# 12. CLASSIFICATION REPORT

print("\n========== CLASSIFICATION REPORT ==========")

print(classification_report(
    y_test,
    y_pred,
    target_names=["Not Churned", "Churned"],
    zero_division=0
))

# 13. CONFUSION MATRIX

cm = confusion_matrix(y_test, y_pred)

plt.figure(figsize=(7, 5))

sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    cmap="Blues",
    xticklabels=["Not Churned", "Churned"],
    yticklabels=["Not Churned", "Churned"]
)

plt.title("Customer Churn Confusion Matrix")
plt.xlabel("Predicted Values")
plt.ylabel("Actual Values")
plt.tight_layout()
plt.show()

# 14. TOP PREDICTIVE FEATURES

feature_names = model.named_steps[
    "preprocessor"
].get_feature_names_out()

coefficients = model.named_steps[
    "classifier"
].coef_[0]

feature_table = pd.DataFrame({
    "Feature": feature_names,
    "Coefficient": coefficients,
    "Importance": np.abs(coefficients)
})

feature_table = feature_table.sort_values(
    by="Importance",
    ascending=False
)

print("\n========== TOP 10 PREDICTIVE FEATURES ==========")

print(feature_table.head(10).to_string(index=False))

# 15. FEATURE IMPORTANCE GRAPH

top_features = feature_table.head(10).sort_values(
    by="Coefficient"
)

plt.figure(figsize=(10, 6))

plt.barh(
    top_features["Feature"],
    top_features["Coefficient"]
)

plt.title("Top Customer Churn Predictive Features")
plt.xlabel("Logistic Regression Coefficient")
plt.ylabel("Features")

plt.tight_layout()
plt.show()

# 16. SAVE MODEL

joblib.dump(model, "customer_churn_model.pkl")

print("\nModel saved successfully!")
print("File Name: customer_churn_model.pkl")

# 17. SAVE DATASET

data.to_csv("customer_churn_dataset.csv", index=False)

print("Dataset saved successfully!")

